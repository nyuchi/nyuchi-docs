// Scans site/src/content/docs/**/*.mdx for `visibility: internal` in
// frontmatter and emits the list of gated URL paths that both the site's
// gate worker (src/worker/gate.ts) and nyuchi-docs-mcp-worker consume as
// their single source of truth for "which pages are private."
//
// Deliberately a standalone regex scan, not the Astro content loader —
// this needs to run before `astro build` (the gate worker imports its
// output) and outside Astro's own build graph. Keep the frontmatter key
// and default in sync with site/src/content.config.ts if either changes.
//
// Outputs:
//   site/src/worker/internal-paths.generated.ts — bundled into the gate
//     worker directly (no runtime fetch needed).
//   site/public/internal-paths.json — served statically at
//     /internal-paths.json so nyuchi-docs-mcp-worker (a separate deploy)
//     can read the same list over HTTP without a cross-package import.

import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const DOCS_ROOT = join(SCRIPT_DIR, '..', 'src', 'content', 'docs');
const WORKER_OUT = join(SCRIPT_DIR, '..', 'src', 'worker', 'internal-paths.generated.ts');
const PUBLIC_OUT = join(SCRIPT_DIR, '..', 'public', 'internal-paths.json');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else if (entry.name.endsWith('.mdx') || entry.name.endsWith('.md')) files.push(full);
  }
  return files;
}

// Mirrors Starlight's own slug derivation closely enough for this purpose:
// strip the docs root, drop the extension, `index` collapses to the parent,
// always ends in a trailing slash to match Starlight's URL convention.
function toUrlPath(file) {
  const rel = relative(DOCS_ROOT, file).replace(/\.mdx?$/, '');
  const withoutIndex = rel.replace(/\/index$/, '').replace(/^index$/, '');
  return `/${withoutIndex}${withoutIndex ? '/' : ''}`;
}

function isInternal(source) {
  const fm = source.match(/^---\n([\s\S]*?)\n---/);
  if (!fm) return false;
  return /^visibility:\s*internal\s*$/m.test(fm[1]);
}

const files = await walk(DOCS_ROOT);
const internalPaths = [];
for (const file of files) {
  const source = await readFile(file, 'utf-8');
  if (isInternal(source)) internalPaths.push(toUrlPath(file));
}
internalPaths.sort();

await mkdir(dirname(WORKER_OUT), { recursive: true });
await writeFile(
  WORKER_OUT,
  `// Generated by scripts/generate-internal-paths.mjs — do not edit by hand.\n` +
    `// Source of truth is the \`visibility: internal\` frontmatter field; re-run\n` +
    `// the generator (wired into \`pnpm build\`) after changing any page's visibility.\n` +
    `export const INTERNAL_PATHS: readonly string[] = ${JSON.stringify(internalPaths, null, 2)};\n`
);
await mkdir(dirname(PUBLIC_OUT), { recursive: true });
await writeFile(PUBLIC_OUT, JSON.stringify({ internalPaths }, null, 2) + '\n');

console.log(`generate-internal-paths: ${internalPaths.length} internal path(s)`);
for (const p of internalPaths) console.log(`  ${p}`);
